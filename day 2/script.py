a = 5
b = 2
print(a + b)   # 7
print(a / b)   # 2.5
print(a ** b)  # 25
print(a * b)   # 10
print(a % b)   # 0

print(a > b)   # True
print(a == b)  # False

print((a > b) and (b < 10))  # True
print((a > b) or (b > 10))   # True
print(not (a == b))          # True