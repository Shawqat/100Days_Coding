# Loops 
# A for loop lets you repeat actions for each item in a sequence.
# A while loop keeps repeating as long as a condition is True.

# Ex 1 : For, range (start, end, step)
for i in range(5):
    print("Iteration:", i)

# Ex 2 : For
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)

# Ex 1 : While 
count = 0
while count < 5:
    print("Count:", count)
    count += 1

# break ends the loop early.
# continue skips the rest of the current iteration.
